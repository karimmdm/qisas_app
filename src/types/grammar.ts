export type SarfPerson = "3rd" | "2nd" | "1st";
export type SarfGender = "masc" | "fem";
export type SarfNumber = "singular" | "dual" | "plural";

export interface SarfVariant {
  person: SarfPerson;
  gender?: SarfGender;
}

export interface SarfInfo {
  family: SarfFamily;
  person: SarfPerson;
  gender?: SarfGender;
  number: SarfNumber;
  /** Valid morphological alternatives (e.g. mudari تَـ singular = 3rd fem OR 2nd masc) */
  alternatives?: SarfVariant[];
}

export interface BreakdownSpan {
  id: string;
  /** [start_token_index, end_token_index] (inclusive) */
  span: [number, number];
  /** Composed roles defining this constituent. Verification checks equality against student selections */
  roles: GrammarRole[];
  /** Category pool to pull distractors from */
  category: GrammarCategory;
  /** Classical implied structure (e.g. "ضَمِيرٌ مُسْتَتِرٌ تَقْدِيرُهُ (هُوَ)") */
  taqdeer?: string;
  /** Scholarly debate / notes (e.g. "البصرة vs الكوفة") */
  note?: string;
  /** Optional Sarf metadata for derived verbs (Forms II–X) */
  sarf?: SarfInfo;
}

export interface Sentence {
  id: string;
  order: number;
  text: string;
  translation: string;
  /** Segmented morpheme tokens in visual order */
  tokens: string[];
  /** Breakdown spans corresponding to Tarkib table rows */
  breakdown: BreakdownSpan[];
}

export interface Chapter {
  id: number;
  title: string;
  translation: string;
  source: string;
  sentences: Sentence[];
}

export interface Story {
  id: number;
  title: string;
  arabicTitle: string;
  translation: string;
  totalChapters: number;
  chapters: Chapter[];
}
