def clean_role(r):
    r = r.strip()
    if r in CANONICAL_ROLES:
        return [r]
    if r in SYNONYMS and SYNONYMS[r] in CANONICAL_ROLES:
        return [SYNONYMS[r]]

    # Parenthetical extraction
    m = re.match(r'^(.*?)\s*\((.*?)\)$', r)
    if m:
        base, inner = m.group(1).strip(), m.group(2).strip()
        matched = []
        for p in [base, inner]:
            cl = clean_role(p)
            for it in cl:
                if it not in matched:
                    matched.append(it)
        if matched:
            return matched

    # Conjunction ' وَ '
    if ' وَ' in r:
        parts = re.split(r'\s+وَ', r)
        matched = []
        for p in parts:
            cl = clean_role(p)
            for it in cl:
                if it not in matched:
                    matched.append(it)
        if matched:
            return matched

    # Substring search
    for c in sorted(CANONICAL_ROLES, key=len, reverse=True):
        if c in r:
            return [c]

    return []

def normalize_story_file(filepath):
    with open(filepath, "r", encoding="utf-8") as f:
        chapters = json.load(f)

    for ch in chapters:
        for sent in ch["sentences"]:
            for b in sent["breakdown"]:
                cleaned_roles = []
                for r in b["roles"]:
                    cl = clean_role(r)
                    if cl:
                        for it in cl:
                            if it not in cleaned_roles:
                                cleaned_roles.append(it)
                if cleaned_roles:
                    b["roles"] = cleaned_roles
                else:
                    # Fallback to category default role
                    cat_defaults = {
                        "huruf": "حَرْفُ جَرٍّ",
                        "afal_naqisah": "فِعْلٌ مَاضٍ نَاقِصٌ",
                        "afal_tammah": "فِعْلٌ مَاضٍ",
                        "marfooat": "فَاعِلٌ",
                        "mansoobat": "مَفْعُولٌ بِهِ",
                        "majroorat": "اِسْمٌ مَجْرُورٌ (بِحَرْفِ الْجَرِّ)",
                        "tawabi": "صِفَةٌ (نَعْتٌ)",
                        "murakkabat": "مُرَكَّبٌ إِضَافِيٌّ",
                        "tarkib_jumla": "جُمْلَةٌ فِعْلِيَّةٌ"
                    }
                    b["roles"] = [cat_defaults.get(b.get("category", "mansoobat"), "مَفْعُولٌ بِهِ")]

    with open(filepath, "w", encoding="utf-8") as f:
        json.dump(chapters, f, ensure_ascii=False, indent=2)

    print(f"✅ Successfully normalized {filepath}")

